def test_T83_ui_payload_full_conversion():
    """T-83: Full UI payload converts to valid YAML with correct fields."""
    from aria.api.routes.runs import _ui_payload_to_mission_yaml
    import yaml
    payload = {
        "topic": "climate change adaptation",
        "intent": "understand local government strategies",
        "depth_level": 3,
        "free_sources": {"web": True, "academic": True, "youtube": False},
        "auth_sources": {},
        "cleaning": {"instructions": "focus on policy"},
    }
    yaml_str = _ui_payload_to_mission_yaml(payload)
    parsed = yaml.safe_load(yaml_str)
    assert parsed["collection"]["topic"] == "climate change adaptation"
    assert parsed["collection"]["depth"] == "high"
    assert "web" in parsed["collection"]["sources"]["enabled"]
    assert "youtube" not in parsed["collection"]["sources"]["enabled"]


