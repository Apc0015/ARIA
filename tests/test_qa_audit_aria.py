def test_T95_raw_store_non_serialisable_datetime(tmp_path):
    """T-95: Document with datetime field serialised as string via default=str."""
    from aria.engine.storage.raw_store import RawStore
    from datetime import datetime, timezone
    store = RawStore(tmp_path / "raw")
    docs = [{"url": "https://x.com", "collected_at": datetime.now(timezone.utc)}]
    path = store.save(docs)
    assert path.exists()
    loaded = store.load()
    assert isinstance(loaded[0]["collected_at"], str), \
        "datetime should be serialised to string via default=str"


