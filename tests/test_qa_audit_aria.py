def test_T101_add_url_case_normalised():
    """T-101: URL normalised to lowercase — HTTPS://X.COM == https://x.com."""
    from aria.engine.memory.shared_memory import SharedMemory
    mem = SharedMemory()
    mem.add_url("HTTPS://EXAMPLE.COM/PATH")
    assert mem.add_url("https://example.com/path") is False


def test_T102_R13_query_param_order_not_normalised():
    """T-102 (R-13 documented): URLs with same params in different order treated as distinct.
    This is a known limitation — not a crash bug but causes semantic duplicates.
    """
    from aria.engine.memory.shared_memory import SharedMemory
    mem = SharedMemory()
    assert mem.add_url("https://x.com/doc?a=1&b=2") is True
    assert mem.add_url("https://x.com/doc?b=2&a=1") is True  # Same URL, different hash


def test_T103_shared_memory_redis_unavailable_falls_back():
    """T-103: Redis at invalid URL → falls back to in-memory dict backend."""
    from aria.engine.memory.shared_memory import SharedMemory
    mem = SharedMemory(backend="redis", redis_url="redis://127.0.0.1:19999")  # invalid port
    assert mem._backend == "dict", "Should fall back to dict when Redis is unreachable"
    assert mem.add_url("https://fallback.com") is True


def test_shared_memory_clear_resets_all():
    """Bonus: clear() removes all tracked URLs and fingerprints."""
    from aria.engine.memory.shared_memory import SharedMemory
    mem = SharedMemory()
    mem.add_url("https://a.com")
    mem.add_fingerprint("fp123")
    mem.clear()
    assert mem.add_url("https://a.com") is True   # seen again after clear
    assert mem.add_fingerprint("fp123") is True


