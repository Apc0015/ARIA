    """T-93 CRITICAL: Save then load returns all documents unchanged."""
    from aria.engine.storage.raw_store import RawStore
    store = RawStore(tmp_path / "raw")
    docs = [
        {"url": "https://a.com", "title": "Article A", "text": "Body A"},
        {"url": "https://b.com", "title": "Article B", "text": "Body B"},
    ]
    store.save(docs)
    loaded = store.load()
    assert len(loaded) == 2
    assert loaded[0]["url"] == "https://a.com"
    assert loaded[1]["title"] == "Article B"


